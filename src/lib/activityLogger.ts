import SOPActivity from '@/models/SOPActivity';
import connectDB from '@/lib/mongodb';

/**
 * Activity Logger - Centralized logging for all SOP activities
 * Captures precise timestamps and detailed user actions
 */

export interface LogActivityParams {
  // SOP Information
  sopId: string;
  sopIdentifier: string;
  sopName: string;
  
  // User Information
  userId: string;
  userName: string;
  userRole: string;
  userDepartment?: string;
  
  // Action Details
  actionType: 'created' | 'updated' | 'reviewed' | 'approved' | 'rejected' | 'downloaded' | 'viewed' | 'expired' | 'deleted' | 'restored' | 'merged';
  actionCategory: 'lifecycle' | 'content' | 'access' | 'compliance' | 'administrative';
  
  // Change Tracking (for updates)
  fieldsChanged?: string[];
  previousValues?: Record<string, any>;
  updatedValues?: Record<string, any>;
  
  // Context
  reason?: string;
  comments?: string;
  
  // Metadata
  ipAddress?: string;
  userAgent?: string;
  sessionId?: string;
  
  // System
  systemGenerated?: boolean;
  requiresApproval?: boolean;
}

/**
 * Log an SOP activity with full timestamp and user tracking
 */
export async function logSOPActivity(params: LogActivityParams) {
  try {
    await connectDB();
    
    const activity = await SOPActivity.create({
      // Core Identifiers
      sopId: params.sopId,
      sopIdentifier: params.sopIdentifier,
      sopName: params.sopName,
      
      // User Information
      userId: params.userId,
      userName: params.userName,
      userRole: params.userRole,
      userDepartment: params.userDepartment,
      
      // Action Details
      actionType: params.actionType,
      actionCategory: params.actionCategory,
      
      // Timestamp (auto-generated by MongoDB)
      timestamp: new Date(),
      
      // Change Tracking
      fieldsChanged: params.fieldsChanged,
      previousValues: params.previousValues,
      updatedValues: params.updatedValues,
      
      // Context
      reason: params.reason,
      comments: params.comments,
      
      // Metadata
      ipAddress: params.ipAddress,
      userAgent: params.userAgent,
      sessionId: params.sessionId,
      
      // System
      systemGenerated: params.systemGenerated || false,
      requiresApproval: params.requiresApproval || false,
    });
    
    return {
      success: true,
      activityId: activity._id.toString(),
      timestamp: activity.timestamp,
    };
  } catch (error: any) {
    console.error('Error logging SOP activity:', error);
    return {
      success: false,
      error: error.message,
    };
  }
}

/**
 * Get activity timeline for a specific SOP
 */
export async function getSOPActivityTimeline(sopId: string, limit: number = 50) {
  try {
    await connectDB();
    
    const activities = await SOPActivity.find({ sopId })
      .sort({ timestamp: -1 })
      .limit(limit)
      .lean();
    
    return {
      success: true,
      activities,
      total: activities.length,
    };
  } catch (error: any) {
    console.error('Error fetching SOP activity timeline:', error);
    return {
      success: false,
      error: error.message,
      activities: [],
    };
  }
}

