/**
 * Get activities by date range
 */
export async function getActivitiesByDateRange(
  startDate: Date,
  endDate: Date,
  filters?: {
    actionType?: string;
    userId?: string;
    department?: string;
    sopId?: string;
  }
) {
  try {
    await connectDB();
    
    const query: any = {
      timestamp: {
        $gte: startDate,
        $lte: endDate,
      },
    };
    
    if (filters?.actionType) query.actionType = filters.actionType;
    if (filters?.userId) query.userId = filters.userId;
    if (filters?.department) query.userDepartment = filters.department;
    if (filters?.sopId) query.sopId = filters.sopId;
    
    const activities = await SOPActivity.find(query)
      .sort({ timestamp: -1 })
      .lean();
    
    return {
      success: true,
      activities,
      total: activities.length,
      dateRange: { startDate, endDate },
    };
  } catch (error: any) {
    console.error('Error fetching activities by date range:', error);
    return {
      success: false,
      error: error.message,
      activities: [],
    };
  }
}

/**
 * Get activity statistics
 */
export async function getActivityStatistics(filters?: {
  startDate?: Date;
  endDate?: Date;
  department?: string;
}) {
  try {
    await connectDB();
    
    const query: any = {};
    
    if (filters?.startDate && filters?.endDate) {
      query.timestamp = {
        $gte: filters.startDate,
        $lte: filters.endDate,
      };
    }
    
    if (filters?.department) {
      query.userDepartment = filters.department;
    }
    
    // Aggregate statistics
    const stats = await SOPActivity.aggregate([
      { $match: query },
      {
        $group: {
          _id: null,
          totalActivities: { $sum: 1 },
          uniqueUsers: { $addToSet: '$userId' },
          uniqueSOPs: { $addToSet: '$sopId' },
          actionTypes: { $push: '$actionType' },
        },
      },
    ]);
    
    // Count by action type
    const actionTypeCounts = await SOPActivity.aggregate([
      { $match: query },
      {
        $group: {
          _id: '$actionType',
          count: { $sum: 1 },
        },
      },
    ]);
    
    // Most active users
    const topUsers = await SOPActivity.aggregate([
      { $match: query },
      {
        $group: {
          _id: { userId: '$userId', userName: '$userName' },
          activityCount: { $sum: 1 },
        },
      },
      { $sort: { activityCount: -1 } },
      { $limit: 10 },
    ]);
    
    return {
      success: true,
      statistics: {
        totalActivities: stats[0]?.totalActivities || 0,
        uniqueUsers: stats[0]?.uniqueUsers?.length || 0,
        uniqueSOPs: stats[0]?.uniqueSOPs?.length || 0,
        actionTypeCounts,
        topUsers,
      },
    };
  } catch (error: any) {
    console.error('Error fetching activity statistics:', error);
    return {
      success: false,
      error: error.message,
    };
  }
}

/**
 * Get recent activities (last 24 hours)
 */
export async function getRecentActivities(hours: number = 24, limit: number = 50) {
  const startDate = new Date();
  startDate.setHours(startDate.getHours() - hours);
  
  return getActivitiesByDateRange(startDate, new Date());
}

/**
 * Compare SOP versions (track what changed)
 */
export function compareSOPVersions(previous: any, updated: any): {
  fieldsChanged: string[];
  previousValues: Record<string, any>;
  updatedValues: Record<string, any>;
} {
  const fieldsChanged: string[] = [];
  const previousValues: Record<string, any> = {};
  const updatedValues: Record<string, any> = {};
  
  // Fields to track
  const trackedFields = [
    'name', 'identifier', 'department', 'owner', 'version',
    'reviewDate', 'expiryDate', 'effectiveDate', 'processArea',
    'guidelineReference', 'remarks', 'status'
  ];
  
  for (const field of trackedFields) {
    if (previous[field] !== updated[field]) {
      fieldsChanged.push(field);
      previousValues[field] = previous[field];
      updatedValues[field] = updated[field];
    }
  }
  
  return { fieldsChanged, previousValues, updatedValues };
}
